"""
学科知识中枢 — 为小说生成系统注入多学科深度

功能：
1. 根据题材自动分配 5 个学科方向
2. 为每个 Agent 提供具体可操作的学科融入指导
3. 支持用户手动指定学科（覆盖自动分配）

设计约束：
- 所有指导文本 2-4 句，直接告诉 Agent "做什么"
- 强调"禁止说教/百科式解释，必须通过情节展现"
- 5 学科 × ~80 字/条 ≈ 400 字/Agent，不显著膨胀 prompt
"""

from dataclasses import dataclass, field


@dataclass
class DisciplineSpec:
    name: str               # "哲学"
    description: str        # 一句话说明对小说的贡献
    agent_guidance: dict     # agent_name → 具体指导文本


# ── 学科池（20 个）──────────────────────────────────────────────────────────────

DISCIPLINE_POOL: dict[str, DisciplineSpec] = {}


def _reg(name: str, description: str, guidance: dict):
    DISCIPLINE_POOL[name] = DisciplineSpec(
        name=name, description=description, agent_guidance=guidance,
    )


