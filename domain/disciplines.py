# ── 核心 API ─────────────────────────────────────────────────────────────────

def resolve_disciplines(
    genre: str,
    user_override: list[str] | None = None,
) -> list[str]:
    """
    解析最终使用的学科列表（5 个）。

    优先级：
    1. 用户手动指定（user_override 非空）
    2. 题材映射
    3. 默认回退
    """
    if user_override:
        # 验证用户指定的学科是否存在于池中
        valid = [d for d in user_override if d in DISCIPLINE_POOL]
        if len(valid) >= 5:
            return valid[:5]
        # 不够 5 个则用映射/默认补齐
        auto = GENRE_DISCIPLINE_MAP.get(genre, _DEFAULT_DISCIPLINES)
        for d in auto:
            if d not in valid and len(valid) < 5:
                valid.append(d)
        # 仍不够则从默认补
        for d in _DEFAULT_DISCIPLINES:
            if d not in valid and len(valid) < 5:
                valid.append(d)
        return valid[:5]

    return GENRE_DISCIPLINE_MAP.get(genre, _DEFAULT_DISCIPLINES)[:5]


def rotate_disciplines(
    base_disciplines: list[str],
    volume_num: int,
    genre: str,
    core_count: int = 3,
    rotation_interval: int = 10,
) -> list[str]:
    """
    长篇学科轮换：保留 core_count 个核心学科，每 rotation_interval 卷轮换其余学科。

    参数：
    - base_disciplines: 初始 5 学科
    - volume_num: 当前卷号
    - genre: 题材类型
    - core_count: 固定不变的核心学科数量
    - rotation_interval: 每隔多少卷轮换一次

    返回：轮换后的 5 学科列表（确定性，同参数同结果）
    """
    if len(base_disciplines) < 5 or volume_num <= rotation_interval:
        return base_disciplines[:5]

    # 核心学科固定
    core = base_disciplines[:core_count]

    # 候选池：所有学科减去核心
    all_disciplines = list(DISCIPLINE_POOL.keys())
    candidates = [d for d in all_disciplines if d not in core]

    if not candidates:
        return base_disciplines[:5]

    # 确定性轮换（种子 = genre hash + 卷号区间）
    rotation_index = (volume_num - 1) // rotation_interval
    import hashlib
    seed = int(hashlib.md5(f"{genre}_{rotation_index}".encode()).hexdigest()[:8], 16)

    # 用种子生成确定性的候选排列
    import random
    rng = random.Random(seed)
    rng.shuffle(candidates)

    # 选取 (5 - core_count) 个轮换学科
    rotate_count = 5 - core_count
    rotated = candidates[:rotate_count]

    result = core + rotated
    return result[:5]


def get_agent_guidance(disciplines: list[str], agent_name: str) -> str:
    """
    汇总多个学科对指定 Agent 的指导文本。
    返回格式化的指导段落，可直接拼接到 system prompt。
    """
    if not disciplines:
        return ""

    sections = []
    for d_name in disciplines:
        spec = DISCIPLINE_POOL.get(d_name)
        if not spec:
            continue
        guidance = spec.agent_guidance.get(agent_name, "")
        if guidance:
            sections.append(f"▸ {d_name}：{guidance}")

    if not sections:
        return ""

    return "\n\n".join(sections)
